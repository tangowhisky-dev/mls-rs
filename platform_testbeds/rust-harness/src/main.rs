/// The directory containing the X.509 test PKI. Defaults to the
/// certificate chains that ship with `mls-rs-crypto-rustcrypto` plus
/// chains generated by `scripts/gen_test_pki.sh`.
fn pki_dir() -> std::path::PathBuf {
    std::env::var("MLS_TEST_PKI_DIR")
        .map(Into::into)
        .unwrap_or_else(|_| {
            std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("../../platform_testbeds/test_pki")
        })
}

/// Simple in-memory [`GroupStateStorage`] used to verify that group
/// state persistence callbacks fire correctly.
#[derive(Debug, Default)]
struct TestStorage {
    state: Mutex<HashMap<Vec<u8>, Vec<u8>>>,
    epochs: Mutex<HashMap<(Vec<u8>, u64), Vec<u8>>>,
}

impl GroupStateStorage for TestStorage {
    fn state(&self, group_id: Vec<u8>) -> Result<Option<Vec<u8>>, mls_rs_uniffi::Error> {
        Ok(self.state.lock().unwrap().get(&group_id).cloned())
    }

    fn epoch(
        &self,
        group_id: Vec<u8>,
        epoch_id: u64,
    ) -> Result<Option<Vec<u8>>, mls_rs_uniffi::Error> {
        Ok(self
            .epochs
            .lock()
            .unwrap()
            .get(&(group_id, epoch_id))
            .cloned())
    }

    fn write(
        &self,
        group_id: Vec<u8>,
        group_state: Vec<u8>,
        epoch_inserts: Vec<EpochRecord>,
        _epoch_updates: Vec<EpochRecord>,
    ) -> Result<(), mls_rs_uniffi::Error> {
        self.state
            .lock()
            .unwrap()
            .insert(group_id.clone(), group_state);
        let mut epochs = self.epochs.lock().unwrap();
        for epoch in epoch_inserts {
            epochs.insert((group_id.clone(), epoch.id), epoch.data);
        }
        Ok(())
    }

    fn max_epoch_id(&self, group_id: Vec<u8>) -> Result<Option<u64>, mls_rs_uniffi::Error> {
        Ok(self
            .epochs
            .lock()
            .unwrap()
            .keys()
            .filter(|(id, _)| *id == group_id)
            .map(|(_, epoch)| *epoch)
            .max())
    }
}

