//! End-to-end test harness for `mls-rs-uniffi` with the RustCrypto
//! backend.
//!
//! This exercises the exact API surface that is exported to Swift,
//! Kotlin and WASM bindings:
//!
//! * `generate_signature_keypair` for every supported cipher suite
//!   (MLS suites 1, 2, 3, 5 and 7),
//! * `Client::new` (basic credentials) and `Client::new_with_x509`
//!   (X.509 credentials backed by the RustCrypto validator),
//! * group creation, key-package generation, `add_members`,
//!   `join_group`, `encrypt_application_message`,
//!   `process_incoming_message`, `commit` and state persistence via
//!   `write_to_storage` / `load_group`.

